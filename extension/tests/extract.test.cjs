const test=require('node:test');
const assert=require('node:assert/strict');
require('../extract.js');
const {clean,plausible}=globalThis.ToxiExtract;
test('extracts composition and stops at nutritional information',()=>assert.equal(clean('Состав: вода, сахар.\nПищевая ценность: 40 ккал'),'вода, сахар'));
test('preserves ingredient names and E codes',()=>assert.equal(clean('Ингредиенты: молоко, E330, ароматизатор пищевой'),'молоко, E330, ароматизатор пищевой'));
test('accepts English heading',()=>assert.equal(clean('Ingredients: water, sugar'),'water, sugar'));
test('rejects missing composition',()=>{assert.equal(plausible('Состав не указан'),false);assert.equal(plausible('состав'),false);});
test('normalizes spaces',()=>assert.equal(clean('Состав:\nвода,\u00a0сахар'),'вода, сахар'));
test('limits candidate length',()=>assert.equal(plausible('а'.repeat(3001)),false));
